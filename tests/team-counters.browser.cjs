const assert = require('node:assert/strict');
const {chromium} = require('playwright');
const url = process.env.TEAM_URL || 'http://127.0.0.1:8028/team-counters.html';
(async () => {
  const browser = await chromium.launch({executablePath:process.env.CHROME_PATH || '/usr/bin/chromium', headless:true});
  const context = await browser.newContext({viewport:{width:390,height:844}});
  const page = await context.newPage(), errors = [], external = [], failed = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => {if (new URL(request.url()).origin !== new URL(url).origin) external.push(request.url());});
  page.on('response', response => {if (response.status() >= 400) failed.push([response.status(),response.url()]);});
  const team = id => page.locator(`.team-button[data-team-id="${id}"]`);
  const variant = id => page.locator(`#variant-tabs [data-variant-id="${id}"]`);
  const result = id => page.locator(`#relation-filters [data-result="${id}"]`);
  try {
    await page.goto(url);
    await team('chengyu').waitFor();
    assert.equal(await page.locator('.team-button').count(),79);
    assert.equal(await page.locator('#team-title').innerText(),'程昱魏智');
    assert.equal(await page.locator('.member').count(),3);
    assert.equal(await page.locator('.member .skill').count(),6);
    assert.equal(await page.locator('.matchup-card').count(),40);
    assert(await page.locator('#load-status').isHidden());
    await page.waitForFunction(() => [...document.querySelectorAll('.member img')].every(i => i.complete && i.naturalWidth > 0));
    await result('disadvantage').click();
    assert.equal(await page.locator('.matchup-section').count(),1);
    assert.equal(await page.locator('.matchup-section').getAttribute('data-result'),'disadvantage');
    await result('disputed').click();
    assert.equal(await page.locator('.matchup-card').count(),3);
    await page.locator('.matchup-card summary').first().click();
    assert(await page.locator('.matchup-card details[open] .source-item').count() >= 2);
    assert.match(await page.locator('.matchup-card details[open]').innerText(),/2025-12-09/);
    await result('all').click();
    await variant('lineups-53-13').click();
    assert.equal(await page.locator('.matchup-card').count(),1);
    assert.equal(await page.locator('.reference-badge').count(),1);
    assert.match(await page.locator('.member').first().innerText(),/风声鹤唳/);
    await variant('lineups-53-13').focus(); await page.keyboard.press('Home');
    assert.equal(await variant('table-a-1').getAttribute('aria-selected'),'true');
    assert.equal(await page.locator('.matchup-card').count(),40);
    assert.equal(new URL(page.url()).searchParams.get('variant'),'table-a-1');
    await page.locator('#team-search').fill('诸葛亮 S3');
    assert(await page.locator('.team-button').count() >= 4);
    assert.equal(await team('chengyu').count(),0);
    await team('zhangfei').click();
    assert.match(await page.locator('.member[data-hero-id="100496"]').innerText(),/蜀 · 弓 · S3/);
    await page.locator('#category').selectOption('蜀骑');
    assert(await page.locator('#search-empty').isVisible());
    assert(await page.locator('#team-details').isHidden());
    await page.locator('#category').selectOption('all');
    assert(await page.locator('#team-details').isVisible());
    await page.locator('#team-search').fill('不存在的队伍');
    assert(await page.locator('#search-empty').isVisible());
    await page.locator('#team-search').fill('');
    await team('liu-huang').click();
    assert.equal(await page.locator('.matchup-card').count(),2);
    await variant('liu-huang-2').click();
    assert.equal(await page.locator('.matchup-card').count(),0);
    assert.match(await page.locator('#matchups').innerText(),/未沿用其他战法方案/);
    assert.match(await page.locator('#variant-notes').innerText(),/空城/);
    await variant('liu-huang-3').click();
    assert.match(await page.locator('.skill.custom').innerText(),/百家·陶渊明/);
    assert.match(await page.locator('#variant-notes').innerText(),/息交克险/);
    await variant('liu-huang-1').click();
    const opponent = page.locator('.matchup-main').first();
    const opponentId = await opponent.getAttribute('data-open-team');
    const opponentVariant = await opponent.getAttribute('data-open-variant');
    await opponent.click();
    assert.equal(await page.locator('.team-button[aria-selected=true]').getAttribute('data-team-id'),opponentId);
    assert.equal(await page.locator('#variant-tabs [aria-selected=true]').getAttribute('data-variant-id'),opponentVariant);
    await page.goBack();
    assert.equal(await page.locator('#team-title').innerText(),'刘徽黄盖法刀');
    await context.grantPermissions(['clipboard-read','clipboard-write']);
    await page.locator('#copy-link').click();
    assert.equal(await page.evaluate(() => navigator.clipboard.readText()), page.url());
    await page.reload(); await variant('liu-huang-1').waitFor();
    assert.equal(await variant('liu-huang-1').getAttribute('aria-selected'),'true');
    await team('chengyu').click();
    for (const width of [320,390,768,1280]) {
      await page.setViewportSize({width,height:900});
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),`page overflow ${width}`);
      assert(await page.evaluate(() => {const l=document.querySelector('.team-column').getBoundingClientRect(), r=document.querySelector('.detail-column').getBoundingClientRect();return l.right <= r.left+1 && Math.abs(l.top-r.top)<1;}),`split columns ${width}`);
      assert(await page.locator('#team-list').evaluate(el => el.scrollHeight > el.clientHeight));
      assert(await page.locator('.detail-body').evaluate(el => el.scrollHeight > el.clientHeight));
      const leftScroll = await page.locator('#team-list').evaluate(el => el.scrollTop);
      await page.locator('.detail-body').evaluate(el => {el.scrollTop=200;});
      assert.equal(await page.locator('#team-list').evaluate(el => el.scrollTop),leftScroll);
      await page.locator('.detail-body').evaluate(el => {el.scrollTop=0;});
    }
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'/tmp/team-counters-mobile.png',fullPage:true});
    await page.setViewportSize({width:1280,height:900});
    await page.screenshot({path:'/tmp/team-counters-desktop.png',fullPage:true});
    await team('chengyu').focus(); await page.keyboard.press('ArrowDown');
    assert.equal(await page.locator('#team-title').innerText(),'春华魏智');
    await page.goto(url+'?team=unknown&variant=unknown'); await team('chengyu').waitFor();
    assert.equal(await page.locator('#team-title').innerText(),'程昱魏智');
    await page.goto(new URL('./',url).href);
    assert.equal(await page.locator('a.tool-card[href="./team-counters.html"]').count(),1);
    assert.deepEqual(errors,[]); assert.deepEqual(external,[]); assert.deepEqual(failed,[]);
    const recovery = await context.newPage();
    let fail = true;
    await recovery.route('**/team-assets/catalog.json*',route => fail ? route.fulfill({status:503,body:'unavailable'}) : route.continue());
    await recovery.goto(url); await recovery.locator('#retry-load').waitFor();
    assert.match(await recovery.locator('#status').innerText(),/载入失败/);
    assert(await recovery.locator('#team-search').isDisabled());
    fail = false; await recovery.locator('#retry-load').click();
    await recovery.locator('.team-button').first().waitFor();
    assert.equal(await recovery.locator('.team-button').count(),79);
    assert(await recovery.locator('#load-status').isHidden());
    assert(!(await recovery.locator('#team-search').isDisabled()));
    await recovery.close();
    console.log('PASS mobile/desktop split scrolling, hero images, independent skill variants, empty/uncertain relations, source details, search, filters, opponent navigation, history, deep links, sharing, keyboard and load recovery');
  } finally {await browser.close();}
})().catch(error => {console.error(error);process.exitCode=1;});
