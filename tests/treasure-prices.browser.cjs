const assert = require('node:assert/strict');
const {chromium} = require('playwright');
const url = process.env.TREASURE_URL || 'http://127.0.0.1:8024/treasure-prices.html';
(async()=>{
  const browser = await chromium.launch({executablePath:process.env.CHROME_PATH || '/usr/bin/chromium',headless:true});
  const page = await browser.newPage({viewport:{width:390,height:844}});
  const errors=[], external=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{if(new URL(request.url()).origin!==new URL(url).origin)external.push(request.url());});
  const weapon = id=>page.locator(`.arm-button[data-weapon-id="${id}"]`);
  const feature = name=>page.getByRole('tab',{name,exact:true});
  const openFilters=async()=>{if(await page.locator('#filter-panel').isHidden())await page.locator('#filter-toggle').click();};
  const closeFilters=async()=>{if(await page.locator('#filter-panel').isVisible())await page.keyboard.press('Escape');};
  const reset=async()=>{await openFilters();await page.locator('#reset-filters').click();await closeFilters();};
  try {
    await page.goto(url+'?weapon=1108&feature=坚忍');
    await page.locator('.arm-button[aria-selected="true"]').waitFor();
    assert.equal(await page.locator('#weapon-title').innerText(),'沧海');
    assert.equal(await page.locator('.arm-button').count(),38);
    assert.equal(await page.locator('#feature-tabs [aria-selected="true"]').innerText(),'坚忍');
    assert.equal(await page.locator('#feature-tabs button').count(),6);
    assert.equal(await page.locator('#price-results .value-option').count(),3);
    assert.equal(await page.locator('.price-value').first().innerText(),'¥552.5');
    assert.match(await page.locator('.hero-skill').innerText(),/被动 · 舍身卫主/);
    await page.waitForFunction(()=>{const image=document.querySelector('.hero-item[data-hero-id="100769"] img');return image.complete&&image.naturalWidth>0;});
    assert.match(await page.locator('.hero-item img').getAttribute('src'),/portrait-thumbs\/.*\.webp$/);
    assert(await page.locator('.hero-item img').first().evaluate(image=>{const r=image.getBoundingClientRect();return r.width/r.height>=.72&&r.width/r.height<=.8;}));
    assert.doesNotMatch(await page.locator('body').innerText(),/参考|红麒|官方|八五折|更新于|¥650/);
    assert.equal(await page.locator('a[href^="http"],footer,.rule-note,.base-note,.no-heroes').count(),0);
    assert(await page.locator('#load-status').isHidden());
    assert.match(await page.locator('#weapon-art').getAttribute('src'),/1108\.jpg$/);
    await page.locator('#base-details summary').click();
    assert.deepEqual(await page.locator('#base-features strong').allTextContents(),['稳固','坚忍','破浪']);
    assert(await page.locator('#base-features').isVisible());
    await page.locator('#base-details summary').click();
    await feature('戒备').click();
    assert.equal(await page.locator('.price-value').first().innerText(),'¥1,020');
    assert.equal(await page.locator('#hero-grid .hero-item').count(),3);
    await page.locator('.value-main').first().click();
    assert.equal(await page.locator('.value-main').first().getAttribute('aria-expanded'),'true');
    await feature('济世').click();
    assert(await page.locator('#adapt-heroes').isHidden());
    await feature('坚忍').click();
    await feature('坚忍').focus();await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('#feature-tabs [aria-selected="true"]').innerText(),'不屈');
    await page.keyboard.press('Home');
    assert.equal(await page.locator('#feature-tabs [aria-selected="true"]').innerText(),'戒备');
    await page.locator('#price-search').fill('典韦');
    await openFilters();
    await page.locator('#main-type-select').selectOption('被动');
    await page.locator('#quality-select').selectOption('粉');
    await page.locator('#max-price').fill('600');await closeFilters();
    await weapon('1108').click();
    assert.equal(await page.locator('#feature-tabs [aria-selected="true"]').innerText(),'坚忍');
    assert.equal(await page.locator('.value-option').count(),1);
    assert.equal(await page.locator('.price-value').innerText(),'¥552.5');
    assert.equal(await page.locator('.value-option[data-quality="红"]').count(),0);
    await reset();await page.locator('#price-search').fill('诸葛亮 S3');
    await openFilters();await page.locator('#main-type-select').selectOption('指挥');await closeFilters();
    assert(await page.locator('.hero-item').count()>0);
    assert(await page.locator('.hero-item').evaluateAll(items=>items.every(item=>item.dataset.heroId==='100496')));
    assert.match(await page.locator('.hero-item').first().innerText(),/蜀 · 弓/);
    assert.match(await page.locator('.hero-name').first().innerText(),/S3诸葛亮/);
    assert.match(await page.locator('.hero-skill').first().innerText(),/指挥 · 明其虚实/);
    await page.locator('#price-search').fill('没有这样的宝物');
    assert(await page.locator('#price-empty').isVisible());
    assert.equal(await page.locator('.value-option').count(),0);
    await reset();await weapon('1117').click();
    assert.deepEqual(await page.locator('#base-features strong').allTextContents(),['安居','课增','繁荣']);
    await page.waitForFunction(()=>{const image=document.getElementById('weapon-art');return image.complete&&image.naturalWidth>0&&image.src.endsWith('/1117.jpg');});
    assert.equal(await page.locator('#weapon-art').getAttribute('alt'),'大吉');
    await weapon('1117').focus();await page.keyboard.press('End');
    assert.equal(await page.locator('#weapon-title').innerText(),'天禄');
    await page.keyboard.press('Home');assert.equal(await page.locator('#weapon-title').innerText(),'游飘');
    await weapon('1108').click();await feature('坚忍').click();
    assert(new URL(page.url()).searchParams.get('feature')==='坚忍');
    for (const width of [320,390,768,1280]) {
      await page.setViewportSize({width,height:900});
      assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`overflow at ${width}px`);
      assert(await page.evaluate(()=>{const left=document.querySelector('.arm-column').getBoundingClientRect(),right=document.querySelector('.value-column').getBoundingClientRect();return left.right<=right.left+1&&Math.abs(left.top-right.top)<=1;}),`columns at ${width}px`);
      assert(await page.locator('#weapon-list').evaluate(el=>el.scrollHeight>el.clientHeight));
      assert.equal(await page.locator('#price-results .value-option').count(),3);
    }
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'/tmp/treasure-prices-mobile.png',fullPage:true});
    await page.setViewportSize({width:1280,height:900});
    await page.screenshot({path:'/tmp/treasure-prices-desktop.png',fullPage:true});
    await page.goto(new URL('./',url).href);
    assert.equal(await page.locator('a.tool-card[href="./treasure-prices.html"]').count(),1);
    await page.goto(new URL('./account.html',url).href);
    await page.locator('#query-button:enabled').waitFor();
    assert.equal(await page.locator('a[href="./treasure-prices.html"]').count(),1);
    assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
    const failed=await browser.newPage();let fail=true;
    await failed.route('**/treasure-assets/prices.json*',route=>fail?route.fulfill({status:503,body:'temporarily unavailable'}):route.continue());
    await failed.goto(url);await failed.locator('#retry-load').waitFor();
    assert.match(await failed.locator('#price-status').innerText(),/载入失败/);
    fail=false;await failed.locator('#retry-load').click();await failed.locator('.arm-button').first().waitFor();
    assert.equal(await failed.locator('.arm-button').count(),38);assert(await failed.locator('#load-status').isHidden());
    console.log('PASS side-by-side mobile/desktop layout, independent list scrolling, weapon/feature selection, prices, portraits, main-skill types, base attributes, filters, keyboard controls, deep links, navigation, and load recovery');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exit(1)});
